-- Описание токена.
--
-- Автор пишет его при запуске, и до сих пор оно уезжало только в
-- метаданные в цепочке: приложение прочитать его не могло, и карточка в
-- мемпаде оставалась без единого слова о том, что это за монета.
--
-- Менять описание после запуска нельзя намеренно — это обещание автора
-- тем, кто покупал, а не подпись под картинкой. Поэтому правки закрыты
-- политикой: строку можно создать со своим описанием, но не переписать
-- задним числом.
--
-- Выполнить в Supabase → SQL Editor.

alter table tokens add column if not exists description text;

-- Длина под то, что помещается в карточку и в описание жетона.
alter table tokens drop constraint if exists tokens_description_len;
alter table tokens add constraint tokens_description_len
  check (description is null or char_length(description) <= 600);

comment on column tokens.description is
  'Описание от автора, задаётся один раз при запуске. Обход дописывает его из метаданных жетона тем токенам, что запущены раньше этой колонки.';
