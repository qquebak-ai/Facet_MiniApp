-- Право удалить свой профиль.
-- Выполнить один раз в Supabase → SQL Editor.
--
-- Кнопка «Удалить аккаунт» удаляет строку в profiles обычным запросом из
-- браузера. Пока на таблице нет разрешения удалять свою строку, запрос
-- молча не удаляет ничего: защита строк отклоняет его, приложение
-- выходит из сессии, и со стороны это выглядит как удаление — а профиль
-- остаётся в базе вместе с ником, описанием и аватаркой.
--
-- Разрешение узкое: удалить можно только собственную строку. Чужую не
-- тронуть, даже зная её идентификатор.

drop policy if exists "delete own profile" on public.profiles;
create policy "delete own profile"
  on public.profiles
  for delete
  to authenticated
  using (auth.uid() = id);

