/* Куда ходить за API.
 *
 * Страницы отдаёт CDN, а обработчики могут жить и там же, и на своём
 * сервере. Разница — один адрес, поэтому она вынесена в переменную
 * сборки: пусто — работают функции рядом с сайтом, задан адрес — все
 * запросы уходят туда. Откат тоже в одну переменную, править код не
 * нужно.
 *
 * Обёртка намеренно тонкая: она не трогает ни заголовки, ни разбор
 * ответа — иначе к ней пришлось бы приводить полсотни мест вызова.
 */

const БАЗА = String(import.meta.env.VITE_API_BASE || "").replace(/\/+$/, "");

/* Полный адрес обработчика. Принимает и «/api/chart?...», и «chart?...» —
   так проще переписывать существующие вызовы. */
export function апи(путь) {
  const п = String(путь || "");
  const хвост = п.startsWith("/api/") ? п : `/api/${п.replace(/^\/+/, "")}`;
  return БАЗА ? `${БАЗА}${хвост}` : хвост;
}

/* Тот же fetch, только адрес приводится к базе.
 *
 * credentials: "omit" — при обращении на чужой домен браузер иначе
 * приложил бы куки, а обработчикам они не нужны: они узнают человека по
 * подписи Telegram или по токену Supabase в теле запроса. */
export function запрос(путь, настройки) {
  return fetch(апи(путь), БАЗА ? { credentials: "omit", ...настройки } : настройки);
}
