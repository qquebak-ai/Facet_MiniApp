/* Приём ошибок приложения.
 *
 * Сюда стекается всё, что сломалось: падения в браузере (window.onerror
 * и необработанные обещания), отказы обработчиков и проверки сторожа.
 * Отсюда оно уходит в Telegram — в тот чат, что указан в WATCH_CHAT.
 *
 * Зачем отдельный обработчик, а не отправка из браузера напрямую в
 * Telegram: токен бота нельзя показывать странице. Здесь же он остаётся
 * на сервере, а страница знает только адрес этого пути.
 *
 * Три вещи, без которых такой канал превращается в шум и его выключают:
 *
 *   • Склейка одинаковых. Одна и та же ошибка у сотни человек — это
 *     одно сообщение со счётчиком, а не сотня одинаковых.
 *   • Потолок частоты. Даже если приложение сходит с ума, в чат уходит
 *     не больше нескольких сообщений в минуту.
 *   • Порог давности. Повторившаяся через час ошибка — новость; та же
 *     ошибка через минуту — та же самая.
 *
 * Переменные окружения:
 *   TELEGRAM_BOT_TOKEN — бот, от чьего имени пишем (тот же, что у бота
 *                        приложения, или отдельный WATCH_BOT_TOKEN).
 *   WATCH_CHAT         — id чата, куда слать. Без него канал выключен.
 *   WATCH_SECRET       — пароль для серверных отправок (сторож, крон).
 *                        Браузеру он не нужен: страница шлёт без него,
 *                        и такие сообщения помечаются как «из браузера».
 */

const BOT = (process.env.WATCH_BOT_TOKEN || process.env.TELEGRAM_BOT_TOKEN || "").trim();
const CHAT = (process.env.WATCH_CHAT || "").trim();
const SECRET = (process.env.WATCH_SECRET || "").trim();

// Одинаковые ошибки склеиваются на этот срок: в пределах часа это одна
// и та же поломка, а не новость.
const ОКНО_ПОВТОРА = 60 * 60 * 1000;
// Больше пяти сообщений в минуту не уходит ни при каких обстоятельствах.
const ПОТОЛОК_В_МИНУТУ = 5;

/* Память живёт в процессе обработчика. На Vercel их несколько, и
   счётчик у каждого свой — но и цель скромная: не дать одному сбою
   залить чат сотней сообщений, а не вести точный учёт. */
const виденные = new Map();
let минута = { начало: 0, счёт: 0 };

const экран = (s) => String(s == null ? "" : s)
  .replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

/* Отпечаток ошибки: по нему решается, новая она или та же самая.
   Числа выкидываем — в них адреса, идентификаторы и время, из-за
   которых одна поломка выглядит десятком разных. */
function отпечаток({ где, текст }) {
  const суть = String(текст || "")
    .split("\n")[0]
    .replace(/0x[0-9a-f]+/gi, "#")
    .replace(/\d+/g, "#")
    .slice(0, 200);
  return `${где}|${суть}`;
}

async function вTelegram(текст) {
  const res = await fetch(`https://api.telegram.org/bot${BOT}/sendMessage`, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({
      chat_id: CHAT,
      text: текст,
      parse_mode: "HTML",
      disable_web_page_preview: true,
      disable_notification: true,
    }),
  });
  return res.ok;
}

export default async function handler(req, res) {
  // Канал выключен — молчим и отвечаем успехом: страница не должна
  // ломаться из-за того, что у площадки не настроен сторож.
  if (!BOT || !CHAT) return res.status(200).json({ ok: true, off: true });
  if (req.method !== "POST") return res.status(405).json({ error: "method_not_allowed" });

  try {
    const тело = typeof req.body === "string" ? JSON.parse(req.body || "{}") : (req.body || {});
    const свой = SECRET && тело.secret === SECRET;

    const где = String(тело.where || (свой ? "server" : "browser")).slice(0, 40);
    const текст = String(тело.message || "").slice(0, 1500);
    if (!текст) return res.status(400).json({ error: "bad_request" });

    const ключ = отпечаток({ где, текст });
    const было = виденные.get(ключ);
    const сейчас = Date.now();

    if (было && сейчас - было.ts < ОКНО_ПОВТОРА) {
      было.счёт += 1;
      было.ts = сейчас;
      // Повтор не шлём, но и не теряем: следующее сообщение об этой же
      // ошибке уйдёт со счётчиком, когда окно истечёт.
      return res.status(200).json({ ok: true, повтор: было.счёт });
    }

    if (сейчас - минута.начало > 60000) минута = { начало: сейчас, счёт: 0 };
    if (минута.счёт >= ПОТОЛОК_В_МИНУТУ) return res.status(200).json({ ok: true, придержано: true });
    минута.счёт += 1;

    const повторов = было ? было.счёт : 0;
    виденные.set(ключ, { ts: сейчас, счёт: 1 });
    // Карта не должна расти бесконечно за долгую жизнь процесса.
    if (виденные.size > 500) {
      for (const [k, v] of виденные) if (сейчас - v.ts > ОКНО_ПОВТОРА) виденные.delete(k);
    }

    const строки = [
      `${свой ? "🛠" : "🌐"} <b>${экран(где)}</b>`,
      `<code>${экран(текст)}</code>`,
    ];
    if (тело.url) строки.push(`↗ ${экран(String(тело.url).slice(0, 200))}`);
    if (тело.user) строки.push(`👤 ${экран(String(тело.user).slice(0, 60))}`);
    if (повторов > 1) строки.push(`🔁 до этого за час: ${повторов}`);

    await вTelegram(строки.join("\n"));
    return res.status(200).json({ ok: true });
  } catch (err) {
    // Сам сторож падать не имеет права: он последний, кто скажет о беде.
    console.warn("[report-error]", err && err.message);
    return res.status(200).json({ ok: false });
  }
}
