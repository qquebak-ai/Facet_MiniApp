/* Рисование картинок на сервере: холст в памяти и сборка PNG.
 *
 * В Node нет ни canvas, ни шрифтов, а тянуть ради одной картинки
 * headless-браузер — это секунды на запрос и сотни мегабайт в функции.
 * Всё, что нужно графику, — линии, заливка и короткие подписи, поэтому
 * холст здесь свой: массив пикселей, несколько примитивов и растровый
 * шрифт 5×7 на латиницу с цифрами. Кириллицы в нём нет намеренно —
 * подписи на картинке только из тикера и чисел.
 *
 * PNG собирается руками: заголовок, сжатые zlib строки пикселей и
 * контрольные суммы. Формат для этого достаточно простой, а внешних
 * зависимостей не появляется вовсе.
 */

import zlib from "node:zlib";

export function createCanvas(width, height, bg = [7, 8, 10]) {
  const data = Buffer.alloc(width * height * 4);
  for (let i = 0; i < width * height; i++) {
    data[i * 4] = bg[0];
    data[i * 4 + 1] = bg[1];
    data[i * 4 + 2] = bg[2];
    data[i * 4 + 3] = 255;
  }
  return { width, height, data };
}

/* Пиксель с наложением по прозрачности. Всё рисование идёт через него,
   поэтому линии и заливки ложатся друг на друга без чёрных швов. */
export function px(c, x, y, [r, g, b], a = 1) {
  const xi = Math.round(x);
  const yi = Math.round(y);
  if (xi < 0 || yi < 0 || xi >= c.width || yi >= c.height || a <= 0) return;
  const i = (yi * c.width + xi) * 4;
  const k = Math.min(1, a);
  c.data[i] = Math.round(c.data[i] * (1 - k) + r * k);
  c.data[i + 1] = Math.round(c.data[i + 1] * (1 - k) + g * k);
  c.data[i + 2] = Math.round(c.data[i + 2] * (1 - k) + b * k);
}

export function fillRect(c, x, y, w, h, color, a = 1) {
  for (let yy = y; yy < y + h; yy++) {
    for (let xx = x; xx < x + w; xx++) px(c, xx, yy, color, a);
  }
}

/* Отрезок толщиной в несколько точек. Своего сглаживания у него нет —
   оно берётся снаружи: картинка рисуется крупнее и потом уменьшается
   усреднением (см. downscale). Так сглаживаются разом и линии, и края
   заливки, и окружности, а не каждая фигура по-своему. */
export function line(c, x0, y0, x1, y1, color, width = 1, a = 1) {
  const dx = x1 - x0;
  const dy = y1 - y0;
  const шагов = Math.max(Math.abs(dx), Math.abs(dy), 1);
  const половина = (width - 1) / 2;
  for (let i = 0; i <= шагов; i++) {
    const x = x0 + (dx * i) / шагов;
    const y = y0 + (dy * i) / шагов;
    for (let oy = -половина; oy <= половина; oy++) {
      for (let ox = -половина; ox <= половина; ox++) px(c, x + ox, y + oy, color, a);
    }
  }
}

