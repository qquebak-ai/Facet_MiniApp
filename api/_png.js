export function textWidth(s, scale = 1) {
  return String(s).length * 6 * scale - scale;
}

/* Подпись. Масштаб целый: дробный дал бы рваные края, а на картинке
   размером в пол-экрана телефона ступеньки видно сразу. */
export function text(c, s, x, y, color, scale = 2, a = 1) {
  let курсор = x;
  for (const ch of String(s).toUpperCase()) {
    const глиф = FONT[ch] || FONT[" "];
    for (let row = 0; row < 7; row++) {
      for (let col = 0; col < 5; col++) {
        if (глиф[row][col] !== "#") continue;
        fillRect(c, курсор + col * scale, y + row * scale, scale, scale, color, a);
      }
    }
    курсор += 6 * scale;
  }
  return курсор;
}

/* Уменьшение с усреднением — то самое сглаживание.
 *
 * Рисовать сразу в нужном размере значит получить ступеньки: пиксель
 * либо закрашен, либо нет, и наклонная линия рассыпается на лесенку.
 * Поэтому всё рисуется в несколько раз крупнее, а здесь каждый блок
 * k×k сворачивается в один пиксель средним цветом: доля закрашенного в
 * блоке и становится плавностью края.
 */
export function downscale(c, k) {
  if (!k || k < 2) return c;
  const w = Math.floor(c.width / k);
  const h = Math.floor(c.height / k);
  const out = { width: w, height: h, data: Buffer.alloc(w * h * 4) };
  const всего = k * k;
  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      let r = 0, g = 0, b = 0;
      for (let yy = 0; yy < k; yy++) {
        const строка = ((y * k + yy) * c.width + x * k) * 4;
        for (let xx = 0; xx < k; xx++) {
          const i = строка + xx * 4;
          r += c.data[i]; g += c.data[i + 1]; b += c.data[i + 2];
        }
      }
      const o = (y * w + x) * 4;
      out.data[o] = Math.round(r / всего);
      out.data[o + 1] = Math.round(g / всего);
      out.data[o + 2] = Math.round(b / всего);
      out.data[o + 3] = 255;
    }
  }
  return out;
}

/* --- сборка PNG --- */

const CRC_TABLE = (() => {
  const t = new Int32Array(256);
  for (let n = 0; n < 256; n++) {
    let c = n;
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    t[n] = c;
  }
  return t;
})();

function crc32(buf) {
  let c = 0xffffffff;
  for (let i = 0; i < buf.length; i++) c = CRC_TABLE[(c ^ buf[i]) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}

function chunk(type, data) {
  const len = Buffer.alloc(4);
  len.writeUInt32BE(data.length, 0);
  const тело = Buffer.concat([Buffer.from(type, "ascii"), data]);
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(тело), 0);
  return Buffer.concat([len, тело, crc]);
}

export function encodePNG(c) {
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(c.width, 0);
  ihdr.writeUInt32BE(c.height, 4);
  ihdr[8] = 8;   // бит на канал
  ihdr[9] = 6;   // RGBA
  ihdr[10] = 0;  // сжатие
  ihdr[11] = 0;  // фильтрация
  ihdr[12] = 0;  // без чересстрочности

  // Каждой строке пикселей PNG требует байт фильтра — ставим 0 («как
  // есть»): предсказание сэкономило бы килобайты, но стоило бы прохода
  // по всей картинке на каждый запрос.
  const строка = c.width * 4;
  const сырое = Buffer.alloc((строка + 1) * c.height);
  for (let y = 0; y < c.height; y++) {
    сырое[y * (строка + 1)] = 0;
    c.data.copy(сырое, y * (строка + 1) + 1, y * строка, (y + 1) * строка);
  }

  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk("IHDR", ihdr),
    chunk("IDAT", zlib.deflateSync(сырое, { level: 6 })),
    chunk("IEND", Buffer.alloc(0)),
  ]);
}
