/* Баннер Mintly.
 *
 * Рисуется здесь, а не в генераторе картинок. У сгенерированного всегда
 * видно происхождение, и не по стилю, а по бессмыслице: точки на линии
 * стоят с разным шагом, свечи внизу не имеют отношения к самой кривой,
 * подписи оси не совпадают с её делениями. Это не поправить промтом —
 * за картинкой просто нет расчёта.
 *
 * Здесь он есть. Кривая — та самая формула площадки: постоянное
 * произведение (виртуальные монеты + собранное) на (виртуальные токены −
 * проданные). Свечи выведены из неё же с воспроизводимым шумом, объём
 * внизу считается из приращений цены, линия поверх свечей — скользящее
 * среднее по их закрытиям, а деления оси стоят на круглых значениях и
 * совпадают с сеткой, потому что сетка по ним и построена.
 *
 * Запуск:  node scripts/make-banner.mjs
 * Выход:   public/banner.svg
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const корень = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

/* --- Палитра приложения (DARK_THEME в src/App.tsx) ------------------- */
const Ц = {
  фон: "#08090B",
  сетка: "#191D24",
  сеткаЯрче: "#242830",
  текст: "#F5F7FA",
  тусклый: "#5F6670",
  серый: "#8B929D",
  акцент: "#6C7CFF",
  рост: "#2ED47A",
  падение: "#F0616D",
};

/* --- Размеры --------------------------------------------------------- */
const Ш = 1792, В = 896;
const поле = { слева: 90, справа: 168, сверху: 96, снизу: 132 };
const графикВерх = поле.сверху;
const графикНиз = В - поле.снизу;
const объёмВерх = графикНиз + 26;
const объёмНиз = В - 46;

/* --- Случайность с памятью -------------------------------------------
   Один и тот же зерно даёт одну и ту же картинку: баннер должен
   пересобираться один в один, иначе его нельзя ни поправить, ни
   сравнить с прошлым. */
function шум(seed) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6D2B79F5) >>> 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/* --- Кривая площадки -------------------------------------------------
   k = (виртуальные SOL + собранное) * (виртуальные токены − проданные).
   Цена — отношение сторон, поэтому по мере выкупа она растёт не линейно,
   а тем быстрее, чем меньше осталось. Числа те же, что в программе
   кривой: 30 виртуальных монет, 1.073 млрд виртуальных токенов, 800 млн
   в продаже. */
const ВИРТ_МОНЕТ = 30;
const ВИРТ_ТОКЕНОВ = 1.073e9;
const В_ПРОДАЖЕ = 8e8;
const K = ВИРТ_МОНЕТ * ВИРТ_ТОКЕНОВ;

const ценаПри = (доля) => K / Math.pow(ВИРТ_ТОКЕНОВ - доля * В_ПРОДАЖЕ, 2);

/* --- Свечи -----------------------------------------------------------
   Шестьдесят отсчётов вдоль кривой. Закрытие каждой — цена кривой в этой
   точке со сдвигом, открытие — закрытие предыдущей: цепочка не рвётся,
   как не рвётся она и на настоящем рынке. Тени растут там, где растёт
   шаг цены, — на крутом участке колебания и правда больше. */
const N = 60;
const слч = шум(20260901);

const свечи = [];
let прошлое = ценаПри(0);
for (let i = 0; i < N; i++) {
  const доля = i / (N - 1);
  const базовая = ценаПри(доля);
  const шаг = базовая - ценаПри(Math.max(0, доля - 1 / (N - 1)));
  // Разброс держится на приращении цены и на самой цене: чем круче
  // участок, тем крупнее свечи, — и часть их обязательно красные.
  // Ровный зелёный ряд бывает только у нарисованного рынка.
  const разброс = (0.5 + слч() * 0.8) * (шаг + базовая * 0.05);
  const закрытие = Math.max(базовая * 0.5, базовая + (слч() - 0.5) * разброс * 2.6);
  const открытие = прошлое;
  const верх = Math.max(открытие, закрытие) + слч() * разброс * 0.9;
  const низ = Math.min(открытие, закрытие) - тень(слч(), разброс);
  свечи.push({ i, открытие, закрытие, верх, низ, растёт: закрытие >= открытие, объём: разброс });
  прошлое = закрытие;
}
function тень(r, разброс) { return r * разброс * 0.9; }

/* Линия поверх свечей — скользящее среднее по закрытиям, центрированное:
   берётся окно по обе стороны от отсчёта. Обычное среднее отстаёт от
   цены и на растущем участке уходит под свечи; центрированное ложится
   ровно посередине, как ему и положено. */
const ОКНО = 3;
const среднее = свечи.map((_, i) => {
  const кусок = свечи.slice(Math.max(0, i - ОКНО), Math.min(свечи.length, i + ОКНО + 1));
  return кусок.reduce((s, c) => s + c.закрытие, 0) / кусок.length;
});

/* --- Пересчёт в пиксели ---------------------------------------------- */
const минЦена = Math.min(...свечи.map((c) => c.низ));
const максЦена = Math.max(...свечи.map((c) => c.верх));
const запас = (максЦена - минЦена) * 0.08;
const нижняяШкала = Math.max(0, минЦена - запас);
const верхняяШкала = максЦена + запас;


const X = (i) => поле.слева + (i / (N - 1)) * (Ш - поле.слева - поле.справа);
const Y = (цена) => графикНиз - ((цена - нижняяШкала) / (верхняяШкала - нижняяШкала)) * (графикНиз - графикВерх);

/* --- Деления оси -----------------------------------------------------
   Круглые значения, а не «сколько влезло»: сетка строится по ним, и
   поэтому подписи стоят ровно на линиях. */
function делениями(мин, макс, сколько = 4) {
  const шаг = (макс - мин) / сколько;
  const порядок = Math.pow(10, Math.floor(Math.log10(шаг)));
  const круглый = [1, 2, 2.5, 5, 10].map((м) => м * порядок).find((м) => м >= шаг) || порядок * 10;
  const первый = Math.ceil(мин / круглый) * круглый;
  const ряд = [];
  for (let v = первый; v <= макс; v += круглый) ряд.push(v);
  return ряд;
}
const деления = делениями(нижняяШкала, верхняяШкала, 4);

// Знаков после запятой ровно столько, сколько нужно шагу деления: иначе
// на одной оси стоят «0.00» и «200», будто это разные величины.
const шагДеления = (деления[1] - деления[0]) * 1e9 || 1;
const знаков = шагДеления >= 10 ? 0 : шагДеления >= 1 ? 1 : 2;
function подписьЦены(v) {
  // Цена кривой — доли монеты за штуку; в подписи она умножена на
  // миллиард, о чём сказано в заголовке оси.
  return (v * 1e9).toFixed(знаков);
}

/* --- Сборка разметки -------------------------------------------------- */
// Оба начертания: латиница для названия, кириллица для подписей. Без
// второго браузер подставляет свой шрифт, и подзаголовок оказывается из
// другой гарнитуры — это первое, что бросается в глаза.
const шрифтЛат = fs.readFileSync(path.join(корень, "public/fonts/jost-latin.woff2")).toString("base64");
const шрифтКир = fs.readFileSync(path.join(корень, "public/fonts/jost-cyrillic.woff2")).toString("base64");

// Последнюю вертикаль не рисуем: она пришлась бы вплотную к свече
// «сейчас» и к узлу на линии — подписи под осью достаточно.
const вертикали = [0, 15, 30, 45];
const вертикалиПодписи = [0, 15, 30, 45, 59];
const времена = ["00:00", "06:00", "12:00", "18:00", "сейчас"];

const ширинаСвечи = ((Ш - поле.слева - поле.справа) / N) * 0.52;

const свечиРазметка = свечи.map((c) => {
  const x = X(c.i);
  const цвет = c.растёт ? Ц.рост : Ц.падение;
  const верхТела = Y(Math.max(c.открытие, c.закрытие));
  const низТела = Y(Math.min(c.открытие, c.закрытие));
  const высота = Math.max(1.5, низТела - верхТела);
  return `    <line x1="${x.toFixed(1)}" y1="${Y(c.верх).toFixed(1)}" x2="${x.toFixed(1)}" y2="${Y(c.низ).toFixed(1)}" stroke="${цвет}" stroke-width="1.1" opacity="0.5"/>
    <rect x="${(x - ширинаСвечи / 2).toFixed(1)}" y="${верхТела.toFixed(1)}" width="${ширинаСвечи.toFixed(1)}" height="${высота.toFixed(1)}" rx="1" fill="${цвет}" opacity="0.62"/>`;
}).join("\n");

const максОбъём = Math.max(...свечи.map((c) => c.объём));
const объёмРазметка = свечи.map((c) => {
  const x = X(c.i);
  const h = (c.объём / максОбъём) * (объёмНиз - объёмВерх);
  return `    <rect x="${(x - ширинаСвечи / 2).toFixed(1)}" y="${(объёмНиз - h).toFixed(1)}" width="${ширинаСвечи.toFixed(1)}" height="${h.toFixed(1)}" rx="1" fill="${c.растёт ? Ц.рост : Ц.падение}" opacity="0.3"/>`;
}).join("\n");

// Линия среднего: гладкая, через середины отрезков — так она не ломается
// на каждом отсчёте, оставаясь при этом по своим точкам.
const точкиЛинии = среднее.map((v, i) => [X(i), Y(v)]);
let путь = `M ${точкиЛинии[0][0].toFixed(1)} ${точкиЛинии[0][1].toFixed(1)}`;
for (let i = 1; i < точкиЛинии.length; i++) {
  const [x0, y0] = точкиЛинии[i - 1];
  const [x1, y1] = точкиЛинии[i];
  const сx = (x0 + x1) / 2;
  путь += ` C ${сx.toFixed(1)} ${y0.toFixed(1)}, ${сx.toFixed(1)} ${y1.toFixed(1)}, ${x1.toFixed(1)} ${y1.toFixed(1)}`;
}
const заливка = `${путь} L ${точкиЛинии[точкиЛинии.length - 1][0].toFixed(1)} ${графикНиз} L ${точкиЛинии[0][0].toFixed(1)} ${графикНиз} Z`;

// Отметки на линии — ровно каждый десятый отсчёт. Равный шаг и есть
// главный признак того, что за точками стоит ряд, а не рука художника.
const отметки = точкиЛинии
  .map(([x, y], i) => (i % 10 === 0 && i !== точкиЛинии.length - 1
    ? `    <circle cx="${x.toFixed(1)}" cy="${y.toFixed(1)}" r="3.4" fill="${Ц.фон}" stroke="${Ц.акцент}" stroke-width="1.6"/>` : null))
  .filter(Boolean).join("\n");

const [xК, yК] = точкиЛинии[точкиЛинии.length - 1];

const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${Ш}" height="${В}" viewBox="0 0 ${Ш} ${В}" font-family="Jost">
  <defs>
    <style>
      @font-face { font-family: 'Jost'; font-weight: 400 700; font-style: normal;
        src: url(data:font/woff2;base64,${шрифтЛат}) format('woff2'); }
      @font-face { font-family: 'Jost'; font-weight: 400 700; font-style: normal;
        unicode-range: U+0400-04FF;
        src: url(data:font/woff2;base64,${шрифтКир}) format('woff2'); }
    </style>
    <linearGradient id="подЛинией" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0%" stop-color="${Ц.акцент}" stop-opacity="0.26"/>
      <stop offset="100%" stop-color="${Ц.акцент}" stop-opacity="0"/>
    </linearGradient>
    <radialGradient id="свет" cx="0.72" cy="0.18" r="0.7">
      <stop offset="0%" stop-color="${Ц.акцент}" stop-opacity="0.13"/>
      <stop offset="100%" stop-color="${Ц.акцент}" stop-opacity="0"/>
    </radialGradient>
    <radialGradient id="узел" cx="0.5" cy="0.5" r="0.5">
      <stop offset="0%" stop-color="${Ц.акцент}" stop-opacity="0.55"/>
      <stop offset="100%" stop-color="${Ц.акцент}" stop-opacity="0"/>
    </radialGradient>
    <linearGradient id="уголок" x1="0" y1="1" x2="1" y2="0">
      <stop offset="0%" stop-color="#000" stop-opacity="0.55"/>
      <stop offset="100%" stop-color="#000" stop-opacity="0"/>
    </linearGradient>
  </defs>

  <rect width="${Ш}" height="${В}" fill="${Ц.фон}"/>
  <rect width="${Ш}" height="${В}" fill="url(#свет)"/>

  <!-- Сетка. Горизонтали стоят на круглых значениях цены, вертикали — на
       отметках времени, и подписи у тех и других те же самые. -->
${деления.map((v) => `  <line x1="${поле.слева}" y1="${Y(v).toFixed(1)}" x2="${Ш - поле.справа}" y2="${Y(v).toFixed(1)}" stroke="${Ц.сетка}" stroke-width="1"/>`).join("\n")}
${вертикали.map((i) => `  <line x1="${X(i).toFixed(1)}" y1="${графикВерх}" x2="${X(i).toFixed(1)}" y2="${объёмНиз}" stroke="${Ц.сетка}" stroke-width="1" opacity="0.6"/>`).join("\n")}

  <!-- Объём: выше там, где цена шла быстрее. Это не украшение, а те же
       числа, из которых построены свечи. -->
${объёмРазметка}

  <!-- Свечи -->
${свечиРазметка}

  <!-- Скользящее среднее по закрытиям -->
  <path d="${заливка}" fill="url(#подЛинией)"/>
  <path d="${путь}" fill="none" stroke="${Ц.акцент}" stroke-width="2.6" stroke-linecap="round" stroke-linejoin="round"/>
${отметки}

  <!-- Последняя точка: её уровень продлён до самой оси, как на терминале -->
  <line x1="${xК.toFixed(1)}" y1="${yК.toFixed(1)}" x2="${Ш - поле.справа + 96}" y2="${yК.toFixed(1)}" stroke="${Ц.акцент}" stroke-width="1" stroke-dasharray="3 5" opacity="0.55"/>
  <circle cx="${xК.toFixed(1)}" cy="${yК.toFixed(1)}" r="26" fill="url(#узел)"/>
  <circle cx="${xК.toFixed(1)}" cy="${yК.toFixed(1)}" r="5.5" fill="${Ц.текст}"/>
  <circle cx="${xК.toFixed(1)}" cy="${yК.toFixed(1)}" r="10" fill="none" stroke="${Ц.акцент}" stroke-width="1.5" opacity="0.75"/>

  <!-- Ось цены -->
${деления.map((v) => `  <text x="${Ш - поле.справа + 16}" y="${(Y(v) + 4).toFixed(1)}" fill="${Ц.тусклый}" font-size="15" letter-spacing="0.04em">${подписьЦены(v)}</text>`).join("\n")}
  <text x="${Ш - поле.справа + 16}" y="${(графикВерх - 22).toFixed(1)}" fill="${Ц.тусклый}" font-size="13" letter-spacing="0.14em">TON ×10⁻⁹</text>

  <!-- Ось времени -->
${вертикалиПодписи.map((i, k) => `  <text x="${X(i).toFixed(1)}" y="${В - 16}" fill="${Ц.тусклый}" font-size="14" text-anchor="${k === 0 ? "start" : k === вертикалиПодписи.length - 1 ? "end" : "middle"}" letter-spacing="0.04em">${времена[k]}</text>`).join("\n")}

  <!-- Затемнение под надписью: слева свечи ещё низкие, но пусть будет
       гарантированный контраст, а не удача раскладки. -->
  <rect x="0" y="${В * 0.28}" width="${Ш * 0.42}" height="${В * 0.62}" fill="url(#уголок)"/>

  <text x="${поле.слева}" y="${В * 0.47}" fill="${Ц.текст}" font-size="104" font-weight="600" letter-spacing="-0.03em">Mintly</text>
  <text x="${поле.слева + 4}" y="${В * 0.47 + 46}" fill="${Ц.серый}" font-size="26" letter-spacing="0.01em">Запуск мемкоинов на TON и Solana</text>
  <g transform="translate(${поле.слева + 4}, ${В * 0.47 + 92})">
    <circle cx="6" cy="-5" r="5" fill="${Ц.рост}"/>
    <text x="20" y="0" fill="${Ц.тусклый}" font-size="20" letter-spacing="0.04em">своя кривая · комиссия 1% · листинг на 85 TON</text>
  </g>
</svg>
`;

fs.mkdirSync(path.join(корень, "public"), { recursive: true });
fs.writeFileSync(path.join(корень, "public/banner.svg"), svg);
console.log(`public/banner.svg — ${Ш}×${В}, свечей ${N}, делений оси ${деления.length}`);
