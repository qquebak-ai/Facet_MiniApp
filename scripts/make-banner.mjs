/* Баннеры Mintly.
 *
 * Рисуются здесь, а не в генераторе картинок. У сгенерированного всегда
 * видно происхождение, и не по стилю, а по бессмыслице: точки на линии
 * стоят с разным шагом, свечи внизу не имеют отношения к кривой над
 * ними, подписи оси не совпадают с делениями сетки. Промтом это не
 * лечится — за картинкой просто нет расчёта.
 *
 * Здесь он есть. Кривая — формула площадки: постоянное произведение
 * (виртуальные монеты + собранное) на (виртуальные токены − проданные).
 * Свечи выведены из неё же с воспроизводимым шумом, объём считается из
 * приращений цены, линия поверх свечей — центрированное скользящее
 * среднее по закрытиям, а сетка построена по круглым значениям, поэтому
 * подписи стоят ровно на её линиях.
 *
 * Размеров три, и это не обрезки одного, а своя раскладка под каждое
 * место: на превью ссылки текст крупнее и деталей меньше, на картинке
 * бота их ещё меньше — подписи оси, уменьшенные втрое, читаются как сор.
 *
 * Запуск:  node scripts/make-banner.mjs
 * Выход:   public/banner.svg + .png       — широкий, 1792×896
 *          public/banner-og.svg + .png    — превью ссылки, 1200×630
 *          public/banner-bot.svg + .png   — картинка бота, 640×360
 *
 * PNG рисует playwright-core, если он установлен (он есть в
 * зависимостях разработки). Без него останутся только SVG.
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const корень = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

/* --- Палитра приложения (DARK_THEME в src/App.tsx) ------------------- */
const Ц = {
  фон: "#08090B",
  сетка: "#191D24",
  текст: "#F5F7FA",
  тусклый: "#5F6670",
  серый: "#8B929D",
  акцент: "#6C7CFF",
  рост: "#2ED47A",
  падение: "#F0616D",
};

/* --- Случайность с памятью -------------------------------------------
   Одно и то же зерно даёт одну и ту же картинку: баннер должен
   пересобираться один в один, иначе его нельзя ни поправить, ни
   сравнить с прошлым. */
function шум(seed) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6D2B79F5) >>> 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/* --- Кривая площадки -------------------------------------------------
   Числа те же, что в программе кривой: 30 виртуальных монет, 1.073 млрд
   виртуальных токенов, 800 млн в продаже. Цена — отношение сторон,
   поэтому по мере выкупа она растёт тем быстрее, чем меньше осталось. */
const ВИРТ_МОНЕТ = 30;
const ВИРТ_ТОКЕНОВ = 1.073e9;
const В_ПРОДАЖЕ = 8e8;
const K = ВИРТ_МОНЕТ * ВИРТ_ТОКЕНОВ;
const ценаПри = (доля) => K / Math.pow(ВИРТ_ТОКЕНОВ - доля * В_ПРОДАЖЕ, 2);

/* Ряд свечей. Закрытие каждой — цена кривой в этой точке со сдвигом,
   открытие — закрытие предыдущей: цепочка не рвётся, как не рвётся она
   и на настоящем рынке. */
function торги(N, seed = 20260901) {
  const слч = шум(seed);
  const ряд = [];
  let прошлое = ценаПри(0);
  for (let i = 0; i < N; i++) {
    const доля = i / (N - 1);
    const базовая = ценаПри(доля);
    const шаг = базовая - ценаПри(Math.max(0, доля - 1 / (N - 1)));
    // Чем круче участок, тем крупнее свечи — и часть их обязательно
    // красные: ровный зелёный ряд бывает только у нарисованного рынка.
    const разброс = (0.5 + слч() * 0.8) * (шаг + базовая * 0.05);
    const закрытие = Math.max(базовая * 0.5, базовая + (слч() - 0.5) * разброс * 2.6);
    const открытие = прошлое;
    const верх = Math.max(открытие, закрытие) + слч() * разброс * 0.9;
    const низ = Math.min(открытие, закрытие) - слч() * разброс * 0.9;
    ряд.push({ i, открытие, закрытие, верх, низ, растёт: закрытие >= открытие, объём: разброс });
    прошлое = закрытие;
  }
  return ряд;
}

/* Центрированное скользящее среднее: обычное отстаёт от цены и на
   растущем участке уходит под свечи, а это ложится ровно посередине. */
function среднееПо(свечи, окно) {
  return свечи.map((_, i) => {
    const кусок = свечи.slice(Math.max(0, i - окно), Math.min(свечи.length, i + окно + 1));
    return кусок.reduce((s, c) => s + c.закрытие, 0) / кусок.length;
  });
}

/* Деления оси: круглые значения, а не «сколько влезло». Сетка строится
   по ним, поэтому подписи стоят ровно на линиях. */
function делениями(мин, макс, сколько) {
  const шаг = (макс - мин) / сколько;
  const порядок = Math.pow(10, Math.floor(Math.log10(шаг)));
  const круглый = [1, 2, 2.5, 5, 10].map((м) => м * порядок).find((м) => м >= шаг) || порядок * 10;
  const первый = Math.ceil(мин / круглый) * круглый;
  const ряд = [];
  for (let v = первый; v <= макс; v += круглый) ряд.push(v);
  return ряд;
}

/* --- Шрифт -----------------------------------------------------------
   Оба начертания зашиваются в файл: без кириллического подзаголовок
   рисуется чужой гарнитурой, и это первое, что бросается в глаза. */
const шрифтЛат = fs.readFileSync(path.join(корень, "public/fonts/jost-latin.woff2")).toString("base64");
const шрифтКир = fs.readFileSync(path.join(корень, "public/fonts/jost-cyrillic.woff2")).toString("base64");

/* --- Раскладка -------------------------------------------------------- */
function нарисовать({ Ш, В, свечей, названиеКегль, подписьКегль, строкаПунктов, осиПодписи, поле }) {
  const свечи = торги(свечей);
  const среднее = среднееПо(свечи, Math.max(2, Math.round(свечей / 20)));

  const графикВерх = поле.сверху;
  const графикНиз = В - поле.снизу;
  const объёмВерх = графикНиз + Math.round(В * 0.03);
  const объёмНиз = В - Math.round(В * 0.05);

  const минЦена = Math.min(...свечи.map((c) => c.низ));
  const максЦена = Math.max(...свечи.map((c) => c.верх));
  const запас = (максЦена - минЦена) * 0.08;
  const низШкалы = Math.max(0, минЦена - запас);
  const верхШкалы = максЦена + запас;

  const X = (i) => поле.слева + (i / (свечей - 1)) * (Ш - поле.слева - поле.справа);
  const Y = (ц) => графикНиз - ((ц - низШкалы) / (верхШкалы - низШкалы)) * (графикНиз - графикВерх);

  const деления = делениями(низШкалы, верхШкалы, осиПодписи ? 4 : 3);
  const шагДеления = ((деления[1] || 0) - деления[0]) * 1e9 || 1;
  const знаков = шагДеления >= 10 ? 0 : шагДеления >= 1 ? 1 : 2;
  const подписьЦены = (v) => (v * 1e9).toFixed(знаков);

  const метки = [0, Math.round(свечей * 0.25), Math.round(свечей * 0.5), Math.round(свечей * 0.75)];
  const времена = ["00:00", "06:00", "12:00", "18:00", "сейчас"];

  const ширинаСвечи = ((Ш - поле.слева - поле.справа) / свечей) * 0.52;
  const тонко = Math.max(0.7, Ш / 1600);

  const свечиРазметка = свечи.map((c) => {
    const x = X(c.i);
    const цвет = c.растёт ? Ц.рост : Ц.падение;
    const верхТела = Y(Math.max(c.открытие, c.закрытие));
    const низТела = Y(Math.min(c.открытие, c.закрытие));
    return `    <line x1="${x.toFixed(1)}" y1="${Y(c.верх).toFixed(1)}" x2="${x.toFixed(1)}" y2="${Y(c.низ).toFixed(1)}" stroke="${цвет}" stroke-width="${(1.1 * тонко).toFixed(1)}" opacity="0.5"/>
    <rect x="${(x - ширинаСвечи / 2).toFixed(1)}" y="${верхТела.toFixed(1)}" width="${ширинаСвечи.toFixed(1)}" height="${Math.max(1.5, низТела - верхТела).toFixed(1)}" rx="1" fill="${цвет}" opacity="0.62"/>`;
  }).join("\n");

  const максОбъём = Math.max(...свечи.map((c) => c.объём));
  const объёмРазметка = свечи.map((c) => {
    const x = X(c.i);
    const h = (c.объём / максОбъём) * (объёмНиз - объёмВерх);
    return `    <rect x="${(x - ширинаСвечи / 2).toFixed(1)}" y="${(объёмНиз - h).toFixed(1)}" width="${ширинаСвечи.toFixed(1)}" height="${h.toFixed(1)}" rx="1" fill="${c.растёт ? Ц.рост : Ц.падение}" opacity="0.3"/>`;
  }).join("\n");

  // Линия гладкая, через середины отрезков: так она не ломается на
  // каждом отсчёте, оставаясь при этом по своим точкам.
  const точки = среднее.map((v, i) => [X(i), Y(v)]);
  let путь = `M ${точки[0][0].toFixed(1)} ${точки[0][1].toFixed(1)}`;
  for (let i = 1; i < точки.length; i++) {
    const [x0, y0] = точки[i - 1];
    const [x1, y1] = точки[i];
    const сx = (x0 + x1) / 2;
    путь += ` C ${сx.toFixed(1)} ${y0.toFixed(1)}, ${сx.toFixed(1)} ${y1.toFixed(1)}, ${x1.toFixed(1)} ${y1.toFixed(1)}`;
  }
  const заливка = `${путь} L ${точки[точки.length - 1][0].toFixed(1)} ${графикНиз} L ${точки[0][0].toFixed(1)} ${графикНиз} Z`;

  // Отметки через равные промежутки. Равный шаг и есть главный признак
  // того, что за точками стоит ряд, а не рука художника.
  const шагОтметок = Math.max(5, Math.round(свечей / 6));
  const отметки = точки
    .map(([x, y], i) => (i % шагОтметок === 0 && i !== точки.length - 1
      ? `    <circle cx="${x.toFixed(1)}" cy="${y.toFixed(1)}" r="${(3.4 * тонко).toFixed(1)}" fill="${Ц.фон}" stroke="${Ц.акцент}" stroke-width="${(1.6 * тонко).toFixed(1)}"/>` : null))
    .filter(Boolean).join("\n");

  const [xК, yК] = точки[точки.length - 1];
  const текстY = В * 0.47;

  return `<svg xmlns="http://www.w3.org/2000/svg" width="${Ш}" height="${В}" viewBox="0 0 ${Ш} ${В}" font-family="Jost">
  <defs>
    <style>
      @font-face { font-family: 'Jost'; font-weight: 400 700; font-style: normal;
        src: url(data:font/woff2;base64,${шрифтЛат}) format('woff2'); }
      @font-face { font-family: 'Jost'; font-weight: 400 700; font-style: normal;
        unicode-range: U+0400-04FF;
        src: url(data:font/woff2;base64,${шрифтКир}) format('woff2'); }
    </style>
    <linearGradient id="подЛинией" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0%" stop-color="${Ц.акцент}" stop-opacity="0.26"/>
      <stop offset="100%" stop-color="${Ц.акцент}" stop-opacity="0"/>
    </linearGradient>
    <radialGradient id="свет" cx="0.72" cy="0.18" r="0.7">
      <stop offset="0%" stop-color="${Ц.акцент}" stop-opacity="0.13"/>
      <stop offset="100%" stop-color="${Ц.акцент}" stop-opacity="0"/>
    </radialGradient>
    <radialGradient id="узел" cx="0.5" cy="0.5" r="0.5">
      <stop offset="0%" stop-color="${Ц.акцент}" stop-opacity="0.55"/>
      <stop offset="100%" stop-color="${Ц.акцент}" stop-opacity="0"/>
    </radialGradient>
    <linearGradient id="уголок" x1="0" y1="1" x2="1" y2="0">
      <stop offset="0%" stop-color="#000" stop-opacity="0.62"/>
      <stop offset="100%" stop-color="#000" stop-opacity="0"/>
    </linearGradient>
  </defs>

  <rect width="${Ш}" height="${В}" fill="${Ц.фон}"/>
  <rect width="${Ш}" height="${В}" fill="url(#свет)"/>

  <!-- Сетка: горизонтали на круглых значениях цены, вертикали на
       отметках времени — те же, что подписаны под осью. -->
${деления.map((v) => `  <line x1="${поле.слева}" y1="${Y(v).toFixed(1)}" x2="${Ш - поле.справа}" y2="${Y(v).toFixed(1)}" stroke="${Ц.сетка}" stroke-width="${тонко.toFixed(1)}"/>`).join("\n")}
${метки.map((i) => `  <line x1="${X(i).toFixed(1)}" y1="${графикВерх}" x2="${X(i).toFixed(1)}" y2="${объёмНиз}" stroke="${Ц.сетка}" stroke-width="${тонко.toFixed(1)}" opacity="0.6"/>`).join("\n")}

  <!-- Объём: выше там, где цена шла быстрее. Не украшение, а те же
       числа, из которых построены свечи. -->
${объёмРазметка}

  <!-- Свечи -->
${свечиРазметка}

  <!-- Скользящее среднее по закрытиям -->
  <path d="${заливка}" fill="url(#подЛинией)"/>
  <path d="${путь}" fill="none" stroke="${Ц.акцент}" stroke-width="${(2.6 * тонко).toFixed(1)}" stroke-linecap="round" stroke-linejoin="round"/>
${отметки}

  <!-- Последняя точка: её уровень продлён до оси, как на терминале -->
  <line x1="${xК.toFixed(1)}" y1="${yК.toFixed(1)}" x2="${(Ш - поле.справа * 0.25).toFixed(1)}" y2="${yК.toFixed(1)}" stroke="${Ц.акцент}" stroke-width="${тонко.toFixed(1)}" stroke-dasharray="3 5" opacity="0.55"/>
  <circle cx="${xК.toFixed(1)}" cy="${yК.toFixed(1)}" r="${(26 * тонко).toFixed(1)}" fill="url(#узел)"/>
  <circle cx="${xК.toFixed(1)}" cy="${yК.toFixed(1)}" r="${(5.5 * тонко).toFixed(1)}" fill="${Ц.текст}"/>
  <circle cx="${xК.toFixed(1)}" cy="${yК.toFixed(1)}" r="${(10 * тонко).toFixed(1)}" fill="none" stroke="${Ц.акцент}" stroke-width="${(1.5 * тонко).toFixed(1)}" opacity="0.75"/>

${осиПодписи ? деления.map((v) => `  <text x="${Ш - поле.справа + 16}" y="${(Y(v) + 4).toFixed(1)}" fill="${Ц.тусклый}" font-size="15" letter-spacing="0.04em">${подписьЦены(v)}</text>`).join("\n") : ""}
${осиПодписи ? `  <text x="${Ш - поле.справа + 16}" y="${(графикВерх - 22).toFixed(1)}" fill="${Ц.тусклый}" font-size="13" letter-spacing="0.14em">TON ×10⁻⁹</text>` : ""}
${осиПодписи ? [...метки, свечей - 1].map((i, k) => `  <text x="${X(i).toFixed(1)}" y="${В - 16}" fill="${Ц.тусклый}" font-size="14" text-anchor="${k === 0 ? "start" : k === метки.length ? "end" : "middle"}" letter-spacing="0.04em">${времена[k]}</text>`).join("\n") : ""}

  <!-- Затемнение под надписью: слева свечи ещё низкие, но пусть контраст
       будет гарантирован, а не выйдет удачей раскладки. -->
  <rect x="0" y="${(В * 0.24).toFixed(0)}" width="${(Ш * 0.46).toFixed(0)}" height="${(В * 0.66).toFixed(0)}" fill="url(#уголок)"/>

  <text x="${поле.слева}" y="${текстY.toFixed(0)}" fill="${Ц.текст}" font-size="${названиеКегль}" font-weight="600" letter-spacing="-0.03em">Mintly</text>
  <text x="${поле.слева + 4}" y="${(текстY + названиеКегль * 0.44).toFixed(0)}" fill="${Ц.серый}" font-size="${подписьКегль}" letter-spacing="0.01em">Запуск мемкоинов на TON и Solana</text>
${строкаПунктов ? `  <g transform="translate(${поле.слева + 4}, ${(текстY + названиеКегль * 0.88).toFixed(0)})">
    <circle cx="6" cy="-5" r="5" fill="${Ц.рост}"/>
    <text x="20" y="0" fill="${Ц.тусклый}" font-size="${Math.round(подписьКегль * 0.78)}" letter-spacing="0.04em">своя кривая · комиссия 1% · листинг на 85 TON</text>
  </g>` : ""}
</svg>
`;
}

/* --- Три места, три раскладки ---------------------------------------- */
const размеры = [
  {
    имя: "banner",           // широкий: канал, шапки, обложки
    Ш: 1792, В: 896, свечей: 60,
    названиеКегль: 104, подписьКегль: 26, строкаПунктов: true, осиПодписи: true,
    поле: { слева: 90, справа: 168, сверху: 96, снизу: 132 },
  },
  {
    имя: "banner-og",        // превью ссылки в Telegram и соцсетях, 1.91:1
    Ш: 1200, В: 630, свечей: 46,
    названиеКегль: 92, подписьКегль: 25, строкаПунктов: true, осиПодписи: false,
    поле: { слева: 64, справа: 72, сверху: 64, снизу: 92 },
  },
  {
    имя: "banner-bot",       // картинка описания бота, 16:9
    Ш: 640, В: 360, свечей: 34,
    названиеКегль: 58, подписьКегль: 16, строкаПунктов: false, осиПодписи: false,
    поле: { слева: 36, справа: 40, сверху: 36, снизу: 48 },
  },
];

const сделанные = [];
for (const р of размеры) {
  const файл = path.join(корень, "public", `${р.имя}.svg`);
  fs.writeFileSync(файл, нарисовать(р));
  сделанные.push({ ...р, файл });
  console.log(`public/${р.имя}.svg — ${р.Ш}×${р.В}, свечей ${р.свечей}`);
}

/* --- PNG -------------------------------------------------------------
   Ни Telegram, ни соцсети SVG в превью не принимают, поэтому рядом
   кладём растр. Рисует его тот же браузер, что показывает страницы, —
   значит и выглядеть будет так же. */
try {
  const { chromium } = await import("playwright-core");
  const браузер = await chromium.launch({ executablePath: process.env.CHROMIUM || "/opt/pw-browsers/chromium" });
  for (const с of сделанные) {
    const стр = await браузер.newPage({ viewport: { width: с.Ш, height: с.В } });
    await стр.goto(`file://${с.файл}`);
    await стр.waitForTimeout(400);
    await стр.screenshot({ path: path.join(корень, "public", `${с.имя}.png`) });
    await стр.close();
    console.log(`public/${с.имя}.png`);
  }
  await браузер.close();
} catch (e) {
  console.log(`PNG пропущены (${(e && e.message) || e}) — SVG на месте`);
}
