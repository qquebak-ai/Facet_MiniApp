/* Сборка api/_fonts.js — шрифтов, вшитых прямо в код.
 *
 * Растровщику картинки нужны файлы шрифтов, а рядом с функцией на
 * площадке никаких файлов проекта нет: там только сам обработчик и его
 * зависимости. Забирать шрифты по сети с собственного сайта оказалось
 * ненадёжно — картинка приходила без единой буквы, потому что ни один
 * из шести файлов до функции не доехал, а увидеть это можно было только
 * по готовому изображению. Вшитые байты никуда не едут.
 *
 * Веса берём тремя отдельными файлами: из переменного шрифта resvg
 * достаёт только начертание по умолчанию, и жирные надписи выходят
 * тонкими. Латиница и кириллица тоже раздельно — это подмножества с
 * сайта шрифтов, вместе они весят под сотню килобайт вместо мегабайта.
 *
 * Запуск: node scripts/make-fonts.mjs
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const корень = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const веса = [500, 700, 800];
const куски = ["latin", "cyrillic"];

const части = [];
let всего = 0;
for (const вес of веса) {
  for (const кусок of куски) {
    const имя = `montserrat-${вес}-${кусок}.woff2`;
    const байты = fs.readFileSync(path.join(корень, "scripts", "fonts", имя));
    всего += байты.length;
    части.push(`  // ${имя}, ${байты.length} Б\n  "${байты.toString("base64")}",`);
  }
}

const текст = `/* Шрифты картинки топа, вшитые в код. Собрано scripts/make-fonts.mjs —
 * руками не править: перегенерировать после замены файлов в
 * scripts/fonts. Почему не по сети и почему веса отдельными файлами —
 * там же, в шапке скрипта.
 */

const БАЗА64 = [
${части.join("\n")}
];

export const ШРИФТЫ = БАЗА64.map((с) => Buffer.from(с, "base64"));
`;

fs.writeFileSync(path.join(корень, "api", "_fonts.js"), текст);
console.log(`api/_fonts.js — ${части.length} файлов, ${Math.round(всего / 1024)} КБ шрифтов`);
