-- только список покупок.
--
-- Ключ покупки — «вид:предмет» (frame:gold, card:meteor): у рамки и
-- карточки бывают одинаковые названия, и по одному имени их не различить.
--
-- Отдельные политики не нужны: колонка читается и пишется вместе с
-- остальным профилем по существующим политикам таблицы profiles.

